import { formatDate, formatPhone, toIsoDateString } from '@/lib/format'
import { DEMO_DOCTOR } from '@/mock/doctor'
import type {
  ConsultationDiagnosis,
  ConsultationPrescriptionItem,
} from '@/types/consultation'
import type { Patient, Sex } from '@/types/patient'
import { APP_NAME } from '@/lib/brand'

const SEX_LABEL: Record<Sex, string> = { male: 'Male', female: 'Female', other: 'Other' }

export interface PrescriptionTextInput {
  patient: Patient
  age: number
  diagnoses: ConsultationDiagnosis[]
  items: ConsultationPrescriptionItem[]
  clinicalNotes: string
  followUpRequired: boolean
  followUpDate: string
  followUpInstructions: string
}

/**
 * Plain-text rendering of the prescription, used by the share sheet and the
 * copy action. Contains only what the doctor entered.
 */
export function buildPrescriptionText({
  patient,
  age,
  diagnoses,
  items,
  clinicalNotes,
  followUpRequired,
  followUpDate,
  followUpInstructions,
}: PrescriptionTextInput): string {
  const lines: string[] = []

  lines.push('DRAFT PRESCRIPTION — REVIEW BEFORE USE')
  lines.push('')
  lines.push(DEMO_DOCTOR.clinicName)
  lines.push(DEMO_DOCTOR.clinicAddress)
  lines.push(`Tel ${formatPhone(DEMO_DOCTOR.clinicPhone)}`)
  lines.push('')
  lines.push(`${DEMO_DOCTOR.fullName}, ${DEMO_DOCTOR.qualifications}`)
  lines.push(`Reg. No. ${DEMO_DOCTOR.registrationNumber}`)
  lines.push('')
  lines.push(`Date: ${formatDate(toIsoDateString())}`)
  lines.push(`Patient: ${patient.fullName} (${patient.id})`)
  lines.push(`Age / Gender: ${age} years, ${SEX_LABEL[patient.sex]}`)

  lines.push(
    `Allergies: ${
      patient.allergies.length === 0
        ? 'No known allergies recorded'
        : patient.allergies
            .map((allergy) => `${allergy.substance} (${allergy.severity})`)
            .join('; ')
    }`,
  )

  lines.push('')
  lines.push('DIAGNOSIS')
  if (diagnoses.length === 0) {
    lines.push('  Not recorded.')
  } else {
    diagnoses.forEach((diagnosis, index) => {
      lines.push(
        `  ${index + 1}. ${diagnosis.name}${diagnosis.notes ? ` — ${diagnosis.notes}` : ''}`,
      )
    })
  }

  lines.push('')
  lines.push('MEDICATION')
  if (items.length === 0) {
    lines.push('  No medication prescribed at this visit.')
  } else {
    items.forEach((item, index) => {
      const name = [item.medication, item.strength].filter(Boolean).join(' ')
      const generic = item.genericName ? ` (${item.genericName})` : ''
      lines.push(`  ${index + 1}. ${name}${generic}`)
      lines.push(
        `     ${item.dose} · ${item.frequency} · ${item.route} · ${item.duration}` +
          (item.quantity ? ` · Qty ${item.quantity}` : ''),
      )
      if (item.instructions) lines.push(`     ${item.instructions}`)
    })
  }

  if (clinicalNotes.trim()) {
    lines.push('')
    lines.push('INSTRUCTIONS')
    lines.push(`  ${clinicalNotes.trim()}`)
  }

  lines.push('')
  lines.push('FOLLOW-UP')
  if (followUpRequired) {
    lines.push(
      `  ${followUpDate ? formatDate(followUpDate) : 'Date not set'}` +
        (followUpInstructions ? ` — ${followUpInstructions}` : ''),
    )
  } else {
    lines.push('  No follow-up required.')
  }

  lines.push('')
  lines.push(
    `Generated by ${APP_NAME}, a demonstration application. Not a valid prescription.`,
  )

  return lines.join('\n')
}
